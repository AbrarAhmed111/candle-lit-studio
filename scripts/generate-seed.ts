/**
 * Writes supabase/seed.sql from the demo data in src/data, so a fresh
 * Supabase project opens with the same catalogue, promotions and settings.
 *
 *   OWNER_EMAIL=you@gmail.com npm run db:seed
 *
 * OWNER_EMAIL is the Google account that becomes the store administrator.
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { seedShop } from '../src/data/admin-seed'
import { store } from '../src/data/store'

const owner = (process.env.OWNER_EMAIL ?? store.email).trim().toLowerCase()
const shop = seedShop()

const q = (v: unknown): string => {
  if (v === null || v === undefined || v === '') return 'null'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (Array.isArray(v)) return `array[${v.map(q).join(', ')}]::text[]`
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`
  return `'${String(v).replace(/'/g, "''")}'`
}
const arr = (v: string[]) => (v.length ? q(v) : `'{}'::text[]`)
const rows = (table: string, cols: string[], values: unknown[][], conflict: string) =>
  values.length === 0
    ? ''
    : `insert into public.${table} (${cols.join(', ')}) values\n${values
        .map(r => `  (${r.join(', ')})`)
        .join(',\n')}\non conflict ${conflict} do nothing;\n`

const s = shop.settings
const out: string[] = [
  '-- Generated by scripts/generate-seed.ts. Run `npm run db:seed` to rebuild.',
  '',
  `insert into public.store_settings (id, name, email, phone, whatsapp, address, announcement, instagram, facebook, shipping_fee, free_shipping_over, delivery_estimate)
values (1, ${[s.name, s.email, s.phone, s.whatsapp, s.address, s.announcement, store.instagram, store.facebook].map(q).join(', ')}, ${s.shippingFee}, ${s.freeShippingOver}, ${q(s.deliveryEstimate)})
on conflict (id) do nothing;\n`,
  rows('couriers', ['name', 'tracking_url', 'active', 'sort'], s.couriers.map((c, i) => [q(c.name), q(c.trackingUrl), q(c.active), i]), '(name)'),
  rows(
    'categories',
    ['slug', 'name', 'description', 'cover', 'sort'],
    shop.categories.map((c, i) => [q(c.slug), q(c.name), q(c.description), q(c.cover), i]),
    '(slug)',
  ),
  rows(
    'products',
    ['id', 'slug', 'name', 'tagline', 'description', 'categories', 'tags', 'fragrance', 'fragrance_family', 'notes', 'wax_type', 'colour', 'dimensions', 'ingredients', 'art', 'images', 'discount_percent', 'sold', 'featured', 'best_seller', 'is_new', 'active', 'created_at'],
    shop.products.map(p => [
      q(p.id), q(p.slug), q(p.name), q(p.tagline), q(p.description), arr(p.categories), arr(p.tags), q(p.fragrance),
      q(p.fragranceFamily), q(p.notes), q(p.waxType), q(p.colour), q(p.dimensions), q(p.ingredients), q(p.art),
      arr(p.images), q(p.discountPercent), p.sold, q(!!p.featured), q(!!p.bestSeller), q(!!p.isNew), q(p.active), q(p.createdAt),
    ]),
    '(id)',
  ),
  rows(
    'variants',
    ['id', 'product_id', 'label', 'sku', 'price', 'stock', 'weight', 'burn_time', 'sort'],
    shop.products.flatMap(p =>
      p.variants.map((v, i) => [q(v.id), q(p.id), q(v.label), q(v.sku), v.price, v.stock, q(v.weight), q(v.burnTime), i]),
    ),
    '(id)',
  ),
  rows(
    'coupons',
    ['code', 'type', 'value', 'min_cart', 'max_discount', 'expires_at', 'description', 'active', 'used', 'max_uses', 'first_order_only', 'per_customer_limit', 'product_ids', 'category_slugs'],
    shop.coupons.map(c => [q(c.code), q(c.type), c.value, q(c.minCart), q(c.maxDiscount), q(c.expiresAt), q(c.description), q(c.active), c.used, q(c.maxUses), q(!!c.firstOrderOnly), q(c.perCustomerLimit), arr(c.productIds ?? []), arr(c.categories ?? [])]),
    '(code)',
  ),
  rows(
    'campaigns',
    ['id', 'name', 'description', 'starts_at', 'ends_at', 'discount_percent', 'categories', 'active'],
    shop.campaigns.map(c => [q(c.id), q(c.name), q(c.description), q(c.startsAt), q(c.endsAt), c.discountPercent, arr(c.categories), q(c.active)]),
    '(id)',
  ),
  // Only the published reviews: the pending ones in the demo are examples
  rows(
    'reviews',
    ['id', 'product_id', 'author', 'city', 'rating', 'title', 'body', 'date', 'verified', 'status'],
    shop.reviews
      .filter(r => r.status === 'Approved')
      .map(r => [q(r.id), q(r.productId), q(r.author), q(r.city), r.rating, q(r.title), q(r.body), q(r.date), q(r.verified), q(r.status)]),
    '(id)',
  ),
  rows(
    'message_templates',
    ['id', 'channel', 'audience', 'name', 'trigger', 'subject', 'body', 'active'],
    shop.templates.map(t => [q(t.id), q(t.channel), q(t.to), q(t.name), q(t.trigger), q(t.subject), q(t.body), q(t.active)]),
    '(id)',
  ),
  rows(
    'team_members',
    ['name', 'email', 'role', 'modules', 'active'],
    [[q('Store owner'), q(owner), q('Administrator'), `'{}'::text[]`, 'true']],
    '(email)',
  ),
  '-- Ratings and review counts come from the approved reviews',
  `update public.products p set
  rating = coalesce((select round(avg(r.rating)::numeric, 1) from public.reviews r where r.product_id = p.id and r.status = 'Approved'), 0),
  review_count = (select count(*) from public.reviews r where r.product_id = p.id and r.status = 'Approved');\n`,
]

writeFileSync(join(__dirname, '..', 'supabase', 'seed.sql'), out.filter(Boolean).join('\n'))
console.log(`supabase/seed.sql written. Administrator: ${owner}`)
